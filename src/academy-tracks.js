export function normalizeTrackWork(value){
 if(value===undefined)return {};
 if(!value||typeof value!=='object'||Array.isArray(value))throw Error('Progreso de itinerario inválido');
 const result={};
 for(const [trackId,entries] of Object.entries(value)){
  const track=academyTracks.find(t=>t.id===trackId);
  if(!track||!entries||typeof entries!=='object'||Array.isArray(entries))throw Error('Itinerario inválido');
  const work={};
  for(const [unitId,entry] of Object.entries(entries)){
   const unit=track.units.find(u=>u.id===unitId);
   if(!unit||!entry||typeof entry.note!=='string'||entry.note.length>1200||!Array.isArray(entry.checked)||entry.checked.length>unit.checks.length||!entry.checked.every(i=>Number.isInteger(i)&&i>=0&&i<unit.checks.length))throw Error('Evidencia inválida');
   work[unitId]={note:entry.note.trim(),checked:[...new Set(entry.checked)]};
  }
  result[trackId]=work;
 }
 return result;
}
export function unitComplete(unit,entry){
 return !!(entry&&typeof entry.note==='string'&&entry.note.trim()&&Array.isArray(entry.checked)&&unit.checks.every((_,i)=>entry.checked.includes(i)));
}
export function trackProgress(track,work={}){
 const done=track.units.filter(u=>unitComplete(u,work[u.id])).length;
 return {done,total:track.units.length,percent:Math.round(done/track.units.length*100)};
}
export function saveTrackUnit(value,trackId,unitId,entry){
 return normalizeTrackWork({...value,[trackId]:{...(value[trackId]||{}),[unitId]:entry}});
}
